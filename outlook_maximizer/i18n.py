def tr(text: str, language: str = "en") -> str:
    """Translate a known UI string, retaining its source when no entry exists."""
    return _EN.get(text, text) if language == "en" else text


def translate_message(text: str, language: str = "en") -> str:
    """Translate app-generated backend notices, never arbitrary email content."""
    if language != "en":
        return text
    if text in _EN:
        return _EN[text]
    text = re.sub(r"偵測到([A-Za-z／]+) 環境設定；非互動使用可能改走第三方服務並依該服務計費。",
                  lambda m: f"{m.group(1).replace('／', '/')} environment settings were detected; non-interactive use may use a third-party service and incur its charges.", text)
    text = re.sub(r"已連線 Outlook（(事件監聽＋選取輪詢|選取輪詢)）",
                  lambda m: "Connected to Outlook (" + ("event listener and selection polling" if m.group(1).startswith("事件") else "selection polling") + ")", text)
    text = re.sub(r"Google 行事曆請求失敗（HTTP (\d+)），請檢查行程資料後重試。",
                  r"Google Calendar request failed (HTTP \1). Check the event and retry.", text)
    text = re.sub(r"無法啟動 ([\w .-]+)。請檢查執行檔路徑與公司端點防護設定。",
                  r"Unable to start \1. Check its executable path and your organization's endpoint security settings.", text)
    text = re.sub(r"([\w .-]+) 執行失敗（代碼 (-?\d+)）。請確認登入、網路與模型設定。",
                  r"\1 failed (exit code \2). Check sign-in, network, and model settings.", text)
    fields = {"行程名稱": "Event title", "地點": "Location", "行程說明": "Event description",
              "信件依據": "Email evidence", "回覆草稿": "Reply draft"}
    text = re.sub(r"([\w\u3400-\u9fff]+) 必須是文字。",
                  lambda m: f"{fields.get(m.group(1), m.group(1))} must be text.", text)
    text = re.sub(r"([\w\u3400-\u9fff]+) 的長度不符合限制。",
                  lambda m: f"{fields.get(m.group(1), m.group(1))} exceeds its length limit.", text)
    text = re.sub(r"([\w]+) 的格式不正確。", r"The \1 format is invalid.", text)
    for source, translated in sorted(_BACKEND.items(), key=lambda item: len(item[0]), reverse=True):
        text = text.replace(source, translated)
    if re.search(r"[\u3400-\u9fff]", text):
        return "An operation could not be completed. Check its settings and try again."
    return text
